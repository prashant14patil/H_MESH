/**
 * ResultPanel.jsx
 * ---------------
 * Displays mesh metadata (vertex count, face count, body model)
 * and provides an OBJ file download button.
 *
 * Props:
 *   meshUrl: string       – URL to fetch/download the OBJ file
 *   metadata: object      – { vertices, faces, body_model } from the API
 *   meshInfo: object|null – { vertices, faces } parsed by the Three.js loader
 *   jobId: string         – used to name the downloaded file
 */

export default function ResultPanel({ meshUrl, metadata = {}, meshInfo = null, jobId = '' }) {
  // Prefer the Three.js parsed values (more accurate), fall back to API metadata
  const vertices = meshInfo?.vertices ?? metadata?.vertices ?? null
  const faces = meshInfo?.faces ?? metadata?.faces ?? null
  const bodyModel = metadata?.body_model ?? 'SMPL'

  const downloadName = jobId ? `body_mesh_${jobId.slice(0, 8)}.obj` : 'body_mesh.obj'

  const stats = [
    {
      label: 'Vertices',
      value: vertices != null ? vertices.toLocaleString() : '—',
      icon: (
        <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
          <path strokeLinecap="round" strokeLinejoin="round"
            d="M12 18.75a6 6 0 006-6v-1.5m-6 7.5a6 6 0 01-6-6v-1.5m6 7.5v3.75m-3.75 0h7.5M12 15.75a3 3 0 01-3-3V4.5a3 3 0 116 0v8.25a3 3 0 01-3 3z" />
        </svg>
      ),
    },
    {
      label: 'Faces',
      value: faces != null ? faces.toLocaleString() : '—',
      icon: (
        <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
          <path strokeLinecap="round" strokeLinejoin="round"
            d="M3.75 6A2.25 2.25 0 016 3.75h2.25A2.25 2.25 0 0110.5 6v2.25a2.25 2.25 0 01-2.25 2.25H6a2.25 2.25 0 01-2.25-2.25V6zM3.75 15.75A2.25 2.25 0 016 13.5h2.25a2.25 2.25 0 012.25 2.25V18a2.25 2.25 0 01-2.25 2.25H6A2.25 2.25 0 013.75 18v-2.25zM13.5 6a2.25 2.25 0 012.25-2.25H18A2.25 2.25 0 0120.25 6v2.25A2.25 2.25 0 0118 10.5h-2.25a2.25 2.25 0 01-2.25-2.25V6zM13.5 15.75a2.25 2.25 0 012.25-2.25H18a2.25 2.25 0 012.25 2.25V18A2.25 2.25 0 0118 20.25h-2.25A2.25 2.25 0 0113.5 18v-2.25z" />
        </svg>
      ),
    },
    {
      label: 'Body model',
      value: bodyModel,
      icon: (
        <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
          <path strokeLinecap="round" strokeLinejoin="round"
            d="M15.75 6a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0zM4.501 20.118a7.5 7.5 0 0114.998 0A17.933 17.933 0 0112 21.75c-2.676 0-5.216-.584-7.499-1.632z" />
        </svg>
      ),
    },
  ]

  return (
    <div className="space-y-4">
      {/* Stat cards */}
      <div className="grid grid-cols-3 gap-3">
        {stats.map((s) => (
          <div
            key={s.label}
            className="flex flex-col gap-1.5 p-3 rounded-xl bg-white border border-gray-200 shadow-sm"
          >
            <div className="flex items-center gap-1.5 text-teal-600">
              {s.icon}
              <span className="text-xs font-medium text-gray-500">{s.label}</span>
            </div>
            <p className="text-lg font-semibold text-gray-800 leading-none">{s.value}</p>
          </div>
        ))}
      </div>

      {/* Disclaimer */}
      <p className="text-xs text-gray-400 leading-relaxed">
        Reconstruction shows estimated external body shape and pose only.
        It does not represent internal body composition, body fat, or muscle mass.
        Generated by HMR2 / 4D-Humans on a GPU cloud instance.
      </p>

      {/* Download button */}
      {meshUrl && (
        <a
          href={meshUrl}
          download={downloadName}
          className="flex items-center justify-center gap-2 w-full px-4 py-2.5 rounded-xl bg-teal-600 hover:bg-teal-700 text-white text-sm font-medium transition-colors shadow-sm"
        >
          <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round"
              d="M3 16.5v2.25A2.25 2.25 0 005.25 21h13.5A2.25 2.25 0 0021 18.75V16.5M16.5 12L12 16.5m0 0L7.5 12m4.5 4.5V3" />
          </svg>
          Download OBJ mesh
        </a>
      )}
    </div>
  )
}
